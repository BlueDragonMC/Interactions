package com.bluedragonmc.interactions.coverage

import com.bluedragonmc.interactions.RuleRegistry
import com.bluedragonmc.interactions.rules.RuleCatalog
import net.minestom.server.MinecraftServer
import net.minestom.server.instance.block.Block
import java.io.File
import kotlin.system.exitProcess

private const val COVERAGE_START = "<!-- coverage -->"
private const val COVERAGE_END = "<!-- /coverage -->"

fun main(args: Array<String>) {
    val root = File(args.firstOrNull { it.startsWith("--root=") }?.substringAfter("--root=") ?: ".")
    val check = args.contains("--check")

    MinecraftServer.init()

    val registry = RuleRegistry()
    RuleCatalog.registerAll(registry)

    val supported: Set<String> = registry.rules()
        .flatMap { it.keys }
        .map { it.asString() }
        .toSet()

    val ignored: Set<String> = File(root, "tools/coverage/ignored-blocks.txt")
        .readLines()
        .map { it.trim() }
        .filter { it.isNotEmpty() && !it.startsWith("#") }
        .toSet()

    val allWithState: List<String> = Block.values()
        .filter { it.properties().isNotEmpty() }
        .map { it.key().asString() }
        .distinct()
        .sorted()

    val universe = allWithState.filter { it !in ignored }
    val supportedInUniverse = universe.filter { it in supported }
    val unsupported = universe.filter { it !in supported }
    val percent = if (universe.isEmpty()) 100 else supportedInUniverse.size * 100 / universe.size

    val coverage = buildCoverageMarkdown(
        totalWithState = allWithState.size,
        ignoredCount = allWithState.size - universe.size,
        coveredCount = supportedInUniverse.size,
        unsupportedCount = unsupported.size,
        percent = percent,
        unsupported = unsupported,
        supported = supportedInUniverse,
    )
    val badge = buildBadge(percent)

    val coverageFile = File(root, "COVERAGE.md")
    val readmeFile = File(root, "README.md")
    val expectedReadme = replaceMarkedSection(readmeFile.readText(), badge)

    if (check) {
        val stale = buildList {
            if (coverageFile.readTextOrNull()?.trim() != coverage.trim()) add("COVERAGE.md")
            if (readmeFile.readText() != expectedReadme) add("README.md coverage badge")
        }
        if (stale.isNotEmpty()) {
            System.err.println("Out of date: ${stale.joinToString()}")
            System.err.println("Run './gradlew :tools:coverage:run' and commit the result.")
            exitProcess(1)
        }
        println("Coverage documentation is up to date ($percent%, ${supportedInUniverse.size}/${universe.size}).")
    } else {
        coverageFile.writeText(coverage)
        if (readmeFile.readText() != expectedReadme) readmeFile.writeText(expectedReadme)
        println("Wrote COVERAGE.md: ${supportedInUniverse.size}/${universe.size} blocks covered ($percent%).")
    }
}

private fun buildCoverageMarkdown(
    totalWithState: Int,
    ignoredCount: Int,
    coveredCount: Int,
    unsupportedCount: Int,
    percent: Int,
    unsupported: List<String>,
    supported: List<String>,
): String {
    return buildString {
        appendLine("# Block Placement Coverage")
        appendLine()
        appendLine("> This file is automatically generated. Do not edit it by hand.")
        appendLine("> Run `./gradlew :tools:coverage:run` to update it; CI fails if it is stale.")
        appendLine()
        appendLine("## Statistics")
        appendLine()
        appendLine("| Metric | Count |")
        appendLine("| --- | ---: |")
        appendLine("| Blocks with state | $totalWithState |")
        appendLine("| Ignored (no custom logic needed) | $ignoredCount |")
        appendLine("| Covered by a rule | $coveredCount |")
        appendLine("| Not yet covered | $unsupportedCount |")
        appendLine("| **Coverage** | **$percent%** ($coveredCount / ${coveredCount + unsupportedCount}) |")
        appendLine()
        appendLine("## Unsupported blocks")
        appendLine()
        if (unsupported.isEmpty()) {
            appendLine("_None._")
        } else {
            unsupported.forEach { appendLine("- [ ] $it") }
        }
        appendLine()
        appendLine("## Supported blocks")
        appendLine()
        if (supported.isEmpty()) {
            appendLine("_None._")
        } else {
            supported.forEach { appendLine("- [x] $it") }
        }
        appendLine()
        appendLine("---")
        appendLine()
        appendLine(
            "Block coverage lists adapted from " +
                "[blocks-and-stuff](https://github.com/everbuild-org/blocks-and-stuff) (MIT) and " +
                "[vibenilla/placement](https://github.com/vibenilla/placement) (Apache-2.0). " +
                "See `THIRD_PARTY_NOTICES.md` for details."
        )
    }
}

private fun buildBadge(percent: Int): String {
    val color = when {
        percent >= 90 -> "brightgreen"
        percent >= 70 -> "green"
        percent >= 50 -> "yellow"
        percent >= 25 -> "orange"
        else -> "red"
    }
    return "![Block placement coverage](https://img.shields.io/badge/block_placement-$percent%25-$color?style=flat-square)"
}

private fun replaceMarkedSection(readme: String, block: String): String {
    val start = readme.indexOf(COVERAGE_START)
    val end = readme.indexOf(COVERAGE_END)
    require(start >= 0 && end > start) {
        "README.md is missing the $COVERAGE_START / $COVERAGE_END markers"
    }
    return readme.substring(0, start + COVERAGE_START.length) +
        "\n" + block + "\n" +
        readme.substring(end)
}

private fun File.readTextOrNull(): String? = if (exists()) readText() else null
